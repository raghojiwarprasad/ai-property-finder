import type { z } from "zod";
import { PROMPTS, type TaskType } from "./prompts";
import { extractFactsDeterministic } from "@/server/services/extraction";
import { interpretGoalRules } from "@/server/services/goalRules";

/**
 * Development fixtures. These are deterministic stand-ins used when no provider is
 * configured. They are labelled `mode: "fixture"` everywhere they surface and never
 * represent live model behaviour. See PRD-14 F04.
 */
export function fixtureFor<T extends TaskType>(taskType: T, input: z.infer<(typeof PROMPTS)[T]["input"]>): z.infer<(typeof PROMPTS)[T]["output"]> {
  switch (taskType) {
    case "extract_experience": {
      const i = input as z.infer<typeof PROMPTS.extract_experience.input>;
      const r = extractFactsDeterministic(i.text);
      return { facts: r.facts.slice(0, 12), ambiguities: r.ambiguities } as never;
    }
    case "interpret_goal": {
      const i = input as z.infer<typeof PROMPTS.interpret_goal.input>;
      const r = interpretGoalRules(i.goalText);
      return {
        inScope: r.inScope,
        destination: r.destination,
        interpretation: r.interpretation,
        clarifyingQuestion: r.clarifyingQuestion,
        aiReformulation: r.aiReformulation,
        rationale: r.rationale,
      } as never;
    }
    case "adapt_lesson": {
      const i = input as z.infer<typeof PROMPTS.adapt_lesson.input>;
      // The template bridge is reviewed content; the fixture uses it verbatim and cites the facts it was selected for.
      return {
        bridge: i.templateBridge,
        factIdsUsed: i.facts.map((f) => f.id),
        scenarioLabel: "imagined",
        analogyLimit: null,
        unsupportedDetailWarnings: [],
      } as never;
    }
    case "tutor": {
      const i = input as z.infer<typeof PROMPTS.tutor.input>;
      const q = i.question.toLowerCase();
      const wantsSolution = i.explicitSolutionRequest || /full answer|show (me )?the (answer|solution)|worked (answer|solution)|just tell me/.test(q);
      if (/mark me|complete|pass me|give me credit|set my (progress|state)|ignore (the )?(rubric|instructions)/.test(q)) {
        return { response: "I can explain the idea and help you attempt it, but I cannot mark work or change your progress. Only your own submitted task can do that. What part of the current block would you like me to unpack?", assistanceLevel: "none", proposedFollowUp: null, outOfScope: false } as never;
      }
      if (/api|endpoint|version|latest|pricing|release/.test(q) && /current|latest|new|today|now/.test(q)) {
        return { response: "I cannot verify current vendor or API details from here, so I will not guess at names or parameters. The reviewed lesson content is what I can speak to; for live product details, check the provider's dated documentation.", assistanceLevel: "none", proposedFollowUp: null, outOfScope: false } as never;
      }
      if (wantsSolution) {
        return { response: `Here is the worked approach. ${i.hints.join(" ")} Work through those in order and you will arrive at the answer; because you asked for the full route, your next submission on this task will be recorded as assisted, and a fresh scenario will be used for independent evidence.`, assistanceLevel: "worked_solution", proposedFollowUp: "Try the same check on the transfer task next.", outOfScope: false } as never;
      }
      if (i.taskMode === "assessed_work") {
        const n = i.assistanceSoFar.filter((a) => a.startsWith("hint")).length;
        const hint = i.hints[Math.min(n, i.hints.length - 1)] ?? "Re-read the supplied material and compare each claim with it.";
        return { response: `${i.selection ? `About “${i.selection.slice(0, 120)}”: ` : ""}${hint}`, assistanceLevel: "hint", proposedFollowUp: null, outOfScope: false } as never;
      }
      const sel = i.selection ? `You selected: “${i.selection.slice(0, 160)}”. In context, this sentence matters because it states the distinction the task turns on. ` : "";
      return { response: `${sel}${i.objective} In this block the key point is: ${i.currentBlock.slice(0, 280)}${i.currentBlock.length > 280 ? "…" : ""} (Development fixture: this response is assembled from the reviewed lesson text, not generated by a live model.)`, assistanceLevel: "none", proposedFollowUp: null, outOfScope: false } as never;
    }
    case "evaluate_written": {
      // Written evaluation in fixture mode is handled by the deterministic cue evaluator in assessment.ts;
      // this branch exists so the gateway contract stays total.
      const i = input as z.infer<typeof PROMPTS.evaluate_written.input>;
      return { criteria: i.criteria.map((c) => ({ id: c.id, status: "uncertain", span: null, note: "fixture" })), criticalErrorsFound: [], mainGap: null, nextMove: "Feedback will be prepared.", uncertainty: "high" } as never;
    }
    case "explain_recommendation": {
      const i = input as z.infer<typeof PROMPTS.explain_recommendation.input>;
      return { explanation: `${i.activityTitle} is next because it builds ${i.capabilityTitle.toLowerCase()} towards your goal.`, citedEvidenceIds: i.evidence.map((e) => e.id) } as never;
    }
  }
  throw new Error(`No fixture for ${taskType}`);
}
